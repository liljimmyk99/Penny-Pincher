// Command genstub reads the generated StrictServerInterface and writes an
// Unimplemented type whose every method returns ErrNotImplemented. Embedding it
// lets a server implement only some operations; the rest answer 501.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"strings"
)

func main() {
	in := flag.String("in", "", "generated file containing StrictServerInterface")
	out := flag.String("out", "", "file to write")
	flag.Parse()

	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, *in, nil, 0)
	if err != nil {
		log.Fatal(err)
	}
	var methods []string
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, sp := range gd.Specs {
			ts, ok := sp.(*ast.TypeSpec)
			if !ok || ts.Name.Name != "StrictServerInterface" {
				continue
			}
			for _, m := range ts.Type.(*ast.InterfaceType).Methods.List {
				name := m.Names[0].Name
				ft := m.Type.(*ast.FuncType)
				req := expr(ft.Params.List[1].Type)
				resp := expr(ft.Results.List[0].Type)
				methods = append(methods, fmt.Sprintf(
					"func (Unimplemented) %s(context.Context, %s) (%s, error) {\n\treturn nil, ErrNotImplemented\n}\n",
					name, req, resp))
			}
		}
	}
	if len(methods) == 0 {
		log.Fatal("StrictServerInterface not found")
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by genstub from openapi.gen.go. DO NOT EDIT.\n\npackage api\n\n")
	b.WriteString("import (\n\t\"context\"\n\t\"errors\"\n)\n\n")
	b.WriteString("// ErrNotImplemented is returned by operations that are in the spec but not built yet.\n")
	b.WriteString("// The HTTP layer turns it into 501 with the standard error body.\n")
	b.WriteString("var ErrNotImplemented = errors.New(\"not implemented\")\n\n")
	b.WriteString("// Unimplemented implements StrictServerInterface with every operation returning ErrNotImplemented.\n")
	b.WriteString("type Unimplemented struct{}\n\n")
	b.WriteString("var _ StrictServerInterface = Unimplemented{}\n\n")
	b.WriteString(strings.Join(methods, "\n"))
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func expr(e ast.Expr) string {
	var b bytes.Buffer
	if err := format.Node(&b, token.NewFileSet(), e); err != nil {
		log.Fatal(err)
	}
	return b.String()
}
